SCHEMA = "motionwright.graph-native-dev-first-save/1"
ALLOW = "allow-one-original-save"
DENY = "deny"
MAX_ORIGINAL = 2 * 1024 * 1024
MAX_RESPONSE = 1024 * 1024
STORE_FILE_LIMIT = 4_194_304
# Keep the original GN1 8 MiB Native child budget and 32 MiB outer
# owner ceiling. The Native producer dynamically shrinks its pending
# result reservation (never raises the parent's budget). An oversized
# actual result fails closed with its unknown original, without retry.
PRIVATE_BYTES = 8 * 1024 * 1024
PRIVATE_FILES = 128


class FirstSaveFailure(Exception):
    def __init__(self, code, *, unknown=False):
        self.code, self.unknown = code, unknown
        super().__init__(code)


def require(condition, code, *, unknown=False):
    if not condition:
        raise FirstSaveFailure(code, unknown=unknown)


def selected(value):
    require(value in (DENY, ALLOW), "GN1_FIRST_SAVE_SELECTOR_CLOSED")
    return value == ALLOW


def digest(raw):
    return hashlib.sha256(raw).hexdigest()


def private_bytes(path, data):
    require(isinstance(path, Path) and type(data) is bytes
            and 0 < len(data) <= MAX_ORIGINAL
            and path.parent.is_dir() and not path.exists() and not path.is_symlink(),
            "GN1_FIRST_SAVE_ORIGINAL_WRITE_ADMISSION")
    with path.open("xb") as stream:
        stream.write(data)
        stream.flush()
        os.fsync(stream.fileno())
    require(path.read_bytes() == data, "GN1_FIRST_SAVE_ORIGINAL_READBACK")
    return {"bytes": len(data), "sha256": digest(data)}


def private_json(path, payload):
    return private_bytes(
        path, (json.dumps(payload, sort_keys=True, separators=(",", ":"),
                          allow_nan=False) + "\n").encode("utf-8"))


def closed_opened_sqlite_witness(response):
    """Accept only a real correlated JSONL result already retained privately.

    The Rust service hashes the identity from its held SQLite pager. Caller
    paths, source fixture IDs and objects cannot replace this live observation.
    """
    require(type(response) is dict and response.get("ok") is True
            and type(response.get("result")) is str
            and re.fullmatch(r"[0-9a-f]{64}", response["result"]) is not None,
            "GN1_FIRST_SAVE_OPENED_SQLITE_WITNESS_INVALID", unknown=True)
    return response["result"]


def require_same_opened_sqlite_witness(writer, reader_response):
    require(type(writer) is str
            and re.fullmatch(r"[0-9a-f]{64}", writer) is not None,
            "GN1_FIRST_SAVE_WRITER_OPENED_SQLITE_WITNESS_MISSING", unknown=True)
    reader = closed_opened_sqlite_witness(reader_response)
    require(reader == writer,
            "GN1_FIRST_SAVE_INDEPENDENT_OPENED_SQLITE_IDENTITY_CHANGED",
            unknown=True)
    return True


def checked_source_fixture(source):
    """Only source generated by native-graph-owner-fixture on this same Store."""
    require(type(source) is dict
            and source.get("schema") == "motionwright.graph-owner-fixture-source/1"
            and source.get("native_authority") is False
            and source.get("graph_persisted") is False
            and type(source.get("project")) is dict
            and type(source.get("graph")) is dict,
            "GN1_FIRST_SAVE_AUTHENTIC_FIXTURE_SOURCE")
    project, graph = source["project"], source["graph"]
    require(type(graph.get("authorship")) is dict
            and type(graph["authorship"].get("source_snapshot")) is dict,
            "GN1_FIRST_SAVE_AUTHENTIC_SOURCE_SNAPSHOT")
    snapshot = graph["authorship"]["source_snapshot"]
    # Native Graph's real source identity is an exact four-field snapshot.
    # A project/generation match alone would admit a stale branch/revision,
    # exhausting the one-shot callback on a source the Store must reject.
    require(type(project.get("id")) is str
            and type(project.get("generation")) is str
            and type(project.get("active_branch")) is str
            and type(project.get("revision")) is int and project["revision"] >= 2
            and source.get("resource") == "project:" + project["id"]
            and type(project.get("scenes")) is list and len(project["scenes"]) > 0
            and type(project.get("deliverables")) is list and len(project["deliverables"]) > 0
            and type(project["scenes"][0]) is dict
            and type(project["deliverables"][0]) is dict
            and snapshot == {
                "project_id": project["id"],
                "generation": project["generation"],
                "branch_id": project["active_branch"],
                "revision": project["revision"],
            }
            and graph.get("scene_id") == project["scenes"][0].get("id")
            and graph.get("variant_profile_ref") == project["deliverables"][0].get("id"),
            "GN1_FIRST_SAVE_SOURCE_SCOPE")
    return {"id": project["id"], "resource": source["resource"],
            "project": project, "graph": graph}


def bounded_process(command, *, env, private, label, timeout=120):
    """One actual host process with immutable, closed private originals."""
    require(type(command) is list and len(command) in (4, 5)
            and all(type(value) is str and value for value in command)
            and Path(command[0]).is_absolute(), "GN1_FIRST_SAVE_CHILD_COMMAND")
    private_json(private / (label + ".intent.original.json"),
                 {"argv": command, "automatic_retry": False, "one_launch": True})
    # subprocess.run(PIPE) collects unbounded output in memory BEFORE it
    # checks timeout or size. A large TimeoutExpired.stdout then fails the
    # secondary private_bytes cap and mislabels a real UNKNOWN effect as a
    # known custody admission failure. Bound BOTH streams while the child runs.
    require(type(timeout) in (int, float) and 0 < timeout <= 120,
            "GN1_FIRST_SAVE_CHILD_TIMEOUT_CONTRACT")
    try:
        child = subprocess.Popen(
            command, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
            stderr=subprocess.PIPE, env=env,
            start_new_session=(os.name == "posix"))
    except OSError:
        raise FirstSaveFailure("GN1_FIRST_SAVE_CHILD_START_UNCERTAIN",
                               unknown=True) from None
    streams = {
        name: {"raw": bytearray(), "observed": 0, "over_cap": False,
               "eof": False, "finished": False, "read_error": False}
        for name in ("stdout", "stderr")
    }
    wake = threading.Event()

    def collect(name, pipe):
        state = streams[name]
        try:
            while True:
                chunk = os.read(pipe.fileno(), 65536)
                if not chunk:
                    state["eof"] = True
                    break
                state["observed"] += len(chunk)
                room = MAX_ORIGINAL - len(state["raw"])
                if room:
                    state["raw"].extend(chunk[:room])
                if state["observed"] > MAX_ORIGINAL:
                    state["over_cap"] = True
                    break
        except OSError:
            state["read_error"] = True
        finally:
            state["finished"] = True
            wake.set()

    readers = [
        threading.Thread(target=collect, args=(name, getattr(child, name)),
                         daemon=True)
        for name in ("stdout", "stderr")
    ]
    for reader in readers:
        reader.start()
    deadline = time.monotonic() + timeout
    first_cause = None
    while True:
        if any(state["over_cap"] for state in streams.values()):
            first_cause = "GN1_FIRST_SAVE_CHILD_STREAM_OVER_BUDGET"
            break
        if any(state["read_error"] for state in streams.values()):
            first_cause = "GN1_FIRST_SAVE_CHILD_PIPE_UNCERTAIN"
            break
        if all(state["finished"] for state in streams.values()) and child.poll() is not None:
            break
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            first_cause = "GN1_FIRST_SAVE_ORIGINAL_PROCESS_TIMEOUT"
            break
        wake.wait(min(remaining, 0.05))
        wake.clear()

    if first_cause is not None:
        # Terminate only this owned process group. A killed/partially
        # dispatched child is UNKNOWN, never classified as not executed.
        try:
            if os.name == "posix":
                os.killpg(child.pid, signal.SIGKILL)
            elif child.poll() is None:
                child.kill()
        except (OSError, ProcessLookupError):
            pass
    try:
        code = child.wait(timeout=3)
    except subprocess.TimeoutExpired:
        first_cause = first_cause or "GN1_FIRST_SAVE_CHILD_TERMINAL_UNCERTAIN"
        try:
            child.kill()
            code = child.wait(timeout=2)
        except (OSError, subprocess.TimeoutExpired):
            code = child.poll()
    for reader in readers:
        reader.join(timeout=1)
    for name in ("stdout", "stderr"):
        getattr(child, name).close()
    if first_cause is None and not all(state["eof"] and state["finished"]
                                       for state in streams.values()):
        first_cause = "GN1_FIRST_SAVE_CHILD_PIPE_UNCERTAIN"

    # No invented newline for a stream which emitted zero observed bytes.
    # An over-budget stream retains at most 2 MiB and explicitly marks that
    # its original is incomplete. A custody failure after dispatch must not
    # replace the first UNKNOWN causal code.
    snapshots = {}
    try:
        for name, state in streams.items():
            raw = bytes(state["raw"])
            retained = (private_bytes(
                private / (label + (".partial-" if first_cause else ".")
                           + name + ".original"), raw) if raw else None)
            snapshots[name] = {
                "observed_bytes_at_least": state["observed"],
                "retained": retained,
                "eof": state["eof"],
                "truncated": state["over_cap"] or not state["eof"],
                "read_error": state["read_error"],
            }
        private_json(private / (label + ".terminal.original.json"), {
            "status": "UNKNOWN" if first_cause else "RETURNED",
            "first_cause": first_cause, "exit_code": code,
            "streams": snapshots, "automatic_retry": False,
        })
    except (OSError, ValueError, FirstSaveFailure):
        raise FirstSaveFailure(
            first_cause or "GN1_FIRST_SAVE_CHILD_CUSTODY_UNCERTAIN",
            unknown=True) from None

    if first_cause:
        raise FirstSaveFailure(first_cause, unknown=True)
    require(code == 0, "GN1_FIRST_SAVE_CHILD_ORIGINAL_ERROR",
            unknown=True)
    try:
        return json.loads(bytes(streams["stdout"]["raw"]))
    except (ValueError, UnicodeError):
        raise FirstSaveFailure("GN1_FIRST_SAVE_CHILD_MALFORMED_ORIGINAL",
                               unknown=True) from None


def seed_original(fixture, database, private, env):
    """One real Store create, editable scene and renderer; Graph is NOT saved."""
    require(not database.exists() and not database.is_symlink()
            and database.parent.is_dir() and private.is_dir(),
            "GN1_FIRST_SAVE_STORE_MUST_BE_FRESH")
    source_file = private / "graph-source.original.json"
    observed = bounded_process(
        [str(fixture), "seed", str(database), str(source_file)],
        env=env, private=private, label="graph-fixture", timeout=120)
    require(observed.get("schema") == "motionwright.graph-owner-fixture-output/1"
            and observed.get("native_authority") is False
            and observed.get("path") == str(source_file)
            and database.is_file() and source_file.is_file(),
            "GN1_FIRST_SAVE_FIXTURE_ORIGINAL_PROVENANCE")
    raw = source_file.read_bytes()
    require(0 < len(raw) <= MAX_ORIGINAL
            and observed.get("bytes") == len(raw),
            "GN1_FIRST_SAVE_FIXTURE_SOURCE_BYTES")
    try:
        parsed = json.loads(raw)
    except (ValueError, UnicodeError):
        raise FirstSaveFailure("GN1_FIRST_SAVE_FIXTURE_SOURCE_MALFORMED") from None
    source = checked_source_fixture(parsed)
    private_json(private / "graph-source-identity.original.json",
                 {"resource": source["resource"], "project_id": source["id"],
                  "source_sha256": digest(raw), "graph_persisted": False,
                  "automatic_retry": False})
    return source


