"""GN1 optional development-only real Graph Save on one disposable native owner.

No R74 reviewer, Graph6 acceptance, broadened sandbox, synthetic Native
authority or automatic replay. The producer owns a fresh SQLite Store and
Semwright connection. Only a separately admitted explicit Save may reach the
actual Native backend; all raw request, response and CLI output remains private.
"""
