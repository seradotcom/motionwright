"""Pure expected-byte derivation for Motionwright's generated Tauri permissions.

Only the current literal build-script form is admitted. This is deliberately
not a Rust interpreter or a general call search: unused functions, macros,
conditional code, aliases and additional statements are not admitted. Whitespace
and comments do not affect the literal command roster.

The caller must authenticate the source Git blob and the pinned Cargo generator
packages, observe pre-build absence, and authenticate/revalidate actual generated
files. This module does no filesystem access, process launch, or network access.

The byte template follows tauri-utils 2.10.1 src/acl/build.rs,
autogenerate_command_permissions, with an empty license_header and schema_ref
false, as selected by tauri-build 2.7.1 src/acl.rs.
"""

from __future__ import annotations

import re

GENERATED_ROOT = "apps/desktop/src-tauri/permissions/autogenerated"
MAX_BUILD_RS_BYTES = 64 * 1024
MAX_COMMANDS = 256
MAX_COMMAND_BYTES = 128
MAX_TOKENS = 4096
MAX_COMMENT_DEPTH = 32
MAX_PERMISSION_BYTES = 4096
MAX_TOTAL_PERMISSION_BYTES = 256 * 1024

# The caller must bind these to the authenticated Cargo.lock/archive identities.
GENERATOR_PACKAGES = (
    ("tauri-build", "2.7.1",
     "59563ca5b331fd97f27ee9672ec8d36d33bb3c9e2c9f6710a1a5687256052e45"),
    ("tauri-utils", "2.10.1",
     "2ff55a614843b9a3f010f211df637c94df2607175b8d0f6e0f4a7c19e18621ee"),
)

_COMMAND = re.compile(r"[A-Za-z][A-Za-z0-9_]*", re.ASCII)
_RESERVED = re.compile(r"(?:CON|PRN|AUX|NUL|COM[1-9]|LPT[1-9])", re.ASCII)

# Any new build.rs logic requires an explicit update to this contract. Support
# is never inferred from a matching literal or call elsewhere in the file.
_PREFIX = (
    "fn main ( ) { let attributes = tauri_build :: Attributes :: new ( ) "
    ". app_manifest ( tauri_build :: AppManifest :: new ( ) "
    ". commands ( & ["
).split()
_SUFFIX_BEFORE_MESSAGE = (
    "] ) ) ; tauri_build :: try_build ( attributes ) . expect ("
).split()


class TauriGeneratedPermissionsError(ValueError):
    """A source form or bounded generated-byte contract was not admitted."""

    def __init__(self, code: str):
        self.code = "tauri_permissions_" + code
        super().__init__(self.code)


def _fail(code: str) -> None:
    raise TauriGeneratedPermissionsError(code)


def _tokens(source: str) -> list[tuple[str, str]]:
    """Tokenize the admitted subset; never search inside comments or strings."""
    result: list[tuple[str, str]] = []
    offset = 0
    length = len(source)
    while offset < length:
        char = source[offset]
        if char in " \t\r\n":
            offset += 1
            continue
        if source.startswith("//", offset):
            end = source.find("\n", offset + 2)
            offset = length if end < 0 else end + 1
            continue
        if source.startswith("/*", offset):
            offset += 2
            depth = 1
            while depth:
                if offset >= length:
                    _fail("unterminated_comment")
                if source.startswith("/*", offset):
                    depth += 1
                    if depth > MAX_COMMENT_DEPTH:
                        _fail("comment_depth_budget")
                    offset += 2
                elif source.startswith("*/", offset):
                    depth -= 1
                    offset += 2
                else:
                    offset += 1
            continue
        if char == '"':
            start = offset
            offset += 1
            while True:
                if offset >= length:
                    _fail("unterminated_string")
                char = source[offset]
                if char in "\r\n":
                    _fail("multiline_string_unsupported")
                if char == '"':
                    offset += 1
                    break
                if char == "\\":
                    offset += 1
                    if offset >= length:
                        _fail("unterminated_string")
                    # Opaque expect messages may contain these ordinary Rust
                    # escapes. Command names below may contain no escapes.
                    if source[offset] not in '\\\"nrt0':
                        _fail("string_escape_unsupported")
                offset += 1
            result.append(("string", source[start:offset]))
        elif char in "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz_":
            start = offset
            offset += 1
            while offset < length and source[offset] in (
                    "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz_0123456789"):
                offset += 1
            result.append(("identifier", source[start:offset]))
        elif source.startswith("::", offset):
            result.append(("punctuation", "::"))
            offset += 2
        elif char in "(){}[],;.= &" and char != " ":
            result.append(("punctuation", char))
            offset += 1
        else:
            _fail("source_token_unsupported")
        if len(result) > MAX_TOKENS:
            _fail("token_budget")
    return result


class _Cursor:
    def __init__(self, tokens: list[tuple[str, str]]):
        self.tokens = tokens
        self.offset = 0

    def peek(self) -> tuple[str, str] | None:
        return self.tokens[self.offset] if self.offset < len(self.tokens) else None

    def expect(self, values: list[str] | tuple[str, ...]) -> None:
        for value in values:
            token = self.peek()
            if token is None or token[0] == "string" or token[1] != value:
                _fail("source_form_unsupported")
            self.offset += 1

    def punctuation(self, value: str) -> bool:
        if self.peek() == ("punctuation", value):
            self.offset += 1
            return True
        return False

    def string(self) -> str:
        token = self.peek()
        if token is None or token[0] != "string":
            _fail("literal_string_required")
        self.offset += 1
        return token[1][1:-1]


def _permission_bytes(command: str) -> bytes:
    slug = command.replace("_", "-")
    return (
        "# Automatically generated - DO NOT EDIT!\n"
        "\n"
        "[[permission]]\n"
        f'identifier = "allow-{slug}"\n'
        f'description = "Enables the {command} command without any pre-configured scope."\n'
        f'commands.allow = ["{command}"]\n'
        "\n"
        "[[permission]]\n"
        f'identifier = "deny-{slug}"\n'
        f'description = "Denies the {command} command without any pre-configured scope."\n'
        f'commands.deny = ["{command}"]\n'
    ).encode("ascii")


def derive_command_permissions(build_rs_bytes: bytes) -> dict[str, bytes]:
    """Return exact repo-relative paths and expected original UTF-8/LF bytes.

    No provenance or physical observation is inferred from this pure result.
    Unsupported syntax, unsafe names, collisions and resource excesses raise
    TauriGeneratedPermissionsError (a ValueError) with a stable prefixed code.
    """
    if type(build_rs_bytes) is not bytes:
        _fail("source_bytes_required")
    if not build_rs_bytes or len(build_rs_bytes) > MAX_BUILD_RS_BYTES:
        _fail("source_byte_budget")
    try:
        source = build_rs_bytes.decode("utf-8")
    except UnicodeDecodeError:
        _fail("source_encoding_invalid")
    if any((ord(char) < 32 and char not in "\t\r\n") or ord(char) == 127
           for char in source):
        _fail("source_control_rejected")
    cursor = _Cursor(_tokens(source))
    cursor.expect(_PREFIX)
    commands: list[str] = []
    seen: set[str] = set()
    folded: set[str] = set()
    while cursor.peek() != ("punctuation", "]"):
        command = cursor.string()
        if "\\" in command:
            _fail("command_escape_unsupported")
        if not command or len(command) > MAX_COMMAND_BYTES:
            _fail("command_byte_budget")
        if _COMMAND.fullmatch(command) is None:
            _fail("command_identifier_invalid")
        if _RESERVED.fullmatch(command.upper()) is not None:
            _fail("command_windows_reserved")
        if command in seen:
            _fail("command_duplicate")
        path_key = (command + ".toml").casefold()
        if path_key in folded:
            _fail("command_path_collision")
        seen.add(command)
        folded.add(path_key)
        commands.append(command)
        if len(commands) > MAX_COMMANDS:
            _fail("command_count_budget")
        if cursor.punctuation(","):
            continue
        if cursor.peek() != ("punctuation", "]"):
            _fail("literal_array_syntax")
    if not commands:
        _fail("command_roster_empty")
    cursor.expect(_SUFFIX_BEFORE_MESSAGE)
    cursor.string()  # The panic message cannot supply commands or Rust tokens.
    cursor.expect((")", ";", "}"))
    if cursor.peek() is not None:
        _fail("source_form_unsupported")

    result: dict[str, bytes] = {}
    total = 0
    for command in commands:
        data = _permission_bytes(command)
        if len(data) > MAX_PERMISSION_BYTES:
            _fail("permission_byte_budget")
        total += len(data)
        if total > MAX_TOTAL_PERMISSION_BYTES:
            _fail("total_permission_byte_budget")
        result[GENERATED_ROOT + "/" + command + ".toml"] = data
    return result
