use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use std::{
    collections::BTreeMap,
    sync::{Arc, Mutex},
    time::{Duration, Instant},
};
use uuid::Uuid;

const GRANT_TTL: Duration = Duration::from_secs(45);
const MAX_ACTIVE_GRANTS: usize = 128;
const MAX_SUBJECT_BYTES: usize = 2_048;
const INVALID_GRANT: &str = "Effect grant is missing, expired, or outside its exact scope.";

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum EffectKind {
    ProjectCreate,
    ProjectEdit,
    ImportLocal,
    RenderLocal,
    DeliverLocal,
    WorkflowMutation,
    RemoteEgress,
    UploadExternal,
    InstallRuntime,
    PublishExternal,
}

impl EffectKind {
    pub fn is_supported_local(self) -> bool {
        matches!(
            self,
            Self::ProjectCreate
                | Self::ProjectEdit
                | Self::ImportLocal
                | Self::RenderLocal
                | Self::DeliverLocal
                | Self::WorkflowMutation
        )
    }

    fn requires_project_scope(self) -> bool {
        matches!(
            self,
            Self::ProjectEdit | Self::RenderLocal | Self::DeliverLocal | Self::WorkflowMutation
        )
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct EffectScope {
    pub project_id: Option<Uuid>,
    pub generation: Option<Uuid>,
    pub revision: Option<u64>,
    // Creation belongs to the trusted AppState/Store session. This value is
    // generated by the desktop backend, never accepted from an IPC request.
    pub workspace_session: Option<Uuid>,
}

impl EffectScope {
    pub fn project(project_id: Uuid, generation: Uuid, revision: u64) -> Self {
        Self {
            project_id: Some(project_id),
            generation: Some(generation),
            revision: Some(revision),
            workspace_session: None,
        }
    }

    pub fn unscoped_import() -> Self {
        Self {
            project_id: None,
            generation: None,
            revision: None,
            workspace_session: None,
        }
    }

    pub fn project_creation(workspace_session: Uuid) -> Self {
        Self {
            workspace_session: Some(workspace_session),
            ..Self::unscoped_import()
        }
    }

    fn validate(self, effect: EffectKind) -> Result<(), String> {
        let complete =
            self.project_id.is_some() && self.generation.is_some() && self.revision.is_some();
        let empty =
            self.project_id.is_none() && self.generation.is_none() && self.revision.is_none();
        if effect == EffectKind::ProjectCreate {
            if !empty
                || self
                    .workspace_session
                    .is_none_or(|session| session.is_nil())
            {
                return Err(
                    "Project creation requires its exact desktop workspace session.".into(),
                );
            }
            return Ok(());
        }
        if self.workspace_session.is_some() {
            return Err("Only project creation accepts a workspace session scope.".into());
        }
        if !complete && !empty {
            return Err("Effect grant project scope must be complete or absent.".into());
        }
        if effect.requires_project_scope() && !complete {
            return Err("This effect requires an exact project generation and revision.".into());
        }
        if !complete && effect != EffectKind::ImportLocal {
            return Err(
                "Only local project import can be granted without an existing project.".into(),
            );
        }
        Ok(())
    }
}

#[derive(Debug, Clone, Serialize)]
pub struct EffectGrantReceipt {
    pub token: Uuid,
    pub effect: EffectKind,
    pub project_id: Option<Uuid>,
    pub generation: Option<Uuid>,
    pub revision: Option<u64>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub workspace_session: Option<Uuid>,
    pub expires_in_seconds: u64,
    pub one_time: bool,
}

#[derive(Debug)]
struct EffectGrantRecord {
    effect: EffectKind,
    scope: EffectScope,
    subject: String,
    expires_at: Instant,
}

#[derive(Clone, Default)]
pub struct EffectGrantRegistry {
    inner: Arc<Mutex<BTreeMap<Uuid, EffectGrantRecord>>>,
}

fn validate_subject(subject: &str) -> Result<(), String> {
    if subject.trim().is_empty()
        || subject.len() > MAX_SUBJECT_BYTES
        || subject.chars().any(char::is_control)
    {
        return Err("Effect grant subject is empty or out of bounds.".into());
    }
    Ok(())
}

/// The caller supplies the invoking window's backend label and the original
/// durable creation intent. No title normalization, retry or receipt authority
/// lives in the grant registry. JSON tuple framing prevents field ambiguity.
pub fn project_creation_subject(
    invoking_window: &str,
    request_id: &str,
    title: &str,
) -> Result<String, String> {
    validate_subject(invoking_window)?;
    validate_subject(request_id)?;
    let bytes = serde_json::to_vec(&(
        "motionwright.project-creation-grant/1",
        invoking_window,
        request_id,
        title,
    ))
    .map_err(|_| "Project creation intent could not be encoded.".to_string())?;
    Ok(format!("project-create:v1:{:x}", Sha256::digest(bytes)))
}

impl EffectGrantRegistry {
    pub fn issue(
        &self,
        effect: EffectKind,
        scope: EffectScope,
        subject: &str,
    ) -> Result<EffectGrantReceipt, String> {
        self.issue_until(effect, scope, subject, Instant::now() + GRANT_TTL)
    }

    fn issue_until(
        &self,
        effect: EffectKind,
        scope: EffectScope,
        subject: &str,
        expires_at: Instant,
    ) -> Result<EffectGrantReceipt, String> {
        if !effect.is_supported_local() {
            return Err(
                "Motionwright does not expose grants for remote egress, upload, runtime installation, or publication."
                    .into(),
            );
        }
        scope.validate(effect)?;
        validate_subject(subject)?;

        let now = Instant::now();
        let mut grants = self
            .inner
            .lock()
            .map_err(|_| "Effect grant registry is unavailable.".to_string())?;
        grants.retain(|_, record| record.expires_at > now);
        if grants.len() >= MAX_ACTIVE_GRANTS {
            return Err("Too many active effect grants; retry after current grants expire.".into());
        }

        let token = Uuid::now_v7();
        grants.insert(
            token,
            EffectGrantRecord {
                effect,
                scope,
                subject: subject.to_owned(),
                expires_at,
            },
        );
        Ok(EffectGrantReceipt {
            token,
            effect,
            project_id: scope.project_id,
            generation: scope.generation,
            revision: scope.revision,
            workspace_session: scope.workspace_session,
            expires_in_seconds: GRANT_TTL.as_secs(),
            one_time: true,
        })
    }

    pub fn consume(
        &self,
        token: Uuid,
        effect: EffectKind,
        scope: EffectScope,
        subject: &str,
    ) -> Result<(), String> {
        scope
            .validate(effect)
            .map_err(|_| INVALID_GRANT.to_string())?;
        validate_subject(subject).map_err(|_| INVALID_GRANT.to_string())?;

        let mut grants = self
            .inner
            .lock()
            .map_err(|_| "Effect grant registry is unavailable.".to_string())?;
        let Some(record) = grants.remove(&token) else {
            return Err(INVALID_GRANT.into());
        };
        if record.expires_at <= Instant::now()
            || record.effect != effect
            || record.scope != scope
            || record.subject != subject
        {
            return Err(INVALID_GRANT.into());
        }
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn scope() -> EffectScope {
        EffectScope::project(Uuid::now_v7(), Uuid::now_v7(), 7)
    }

    #[test]
    fn exact_grant_is_one_time() {
        let registry = EffectGrantRegistry::default();
        let scope = scope();
        let grant = registry
            .issue(EffectKind::ProjectEdit, scope, "request:edit-1")
            .unwrap();

        registry
            .consume(
                grant.token,
                EffectKind::ProjectEdit,
                scope,
                "request:edit-1",
            )
            .unwrap();
        assert!(
            registry
                .consume(
                    grant.token,
                    EffectKind::ProjectEdit,
                    scope,
                    "request:edit-1",
                )
                .is_err()
        );
    }

    #[test]
    fn grant_never_crosses_effect_boundaries_and_mismatch_consumes_it() {
        let registry = EffectGrantRegistry::default();
        let scope = scope();
        let grant = registry
            .issue(EffectKind::ProjectEdit, scope, "request:edit-2")
            .unwrap();

        assert!(
            registry
                .consume(
                    grant.token,
                    EffectKind::RenderLocal,
                    scope,
                    "request:edit-2",
                )
                .is_err()
        );
        assert!(
            registry
                .consume(
                    grant.token,
                    EffectKind::ProjectEdit,
                    scope,
                    "request:edit-2",
                )
                .is_err()
        );
    }

    #[test]
    fn project_generation_revision_and_subject_are_exact() {
        let registry = EffectGrantRegistry::default();
        let scope = scope();
        let grant = registry
            .issue(EffectKind::DeliverLocal, scope, "/tmp/master.otio")
            .unwrap();
        let changed_revision = EffectScope::project(
            scope.project_id.unwrap(),
            scope.generation.unwrap(),
            scope.revision.unwrap() + 1,
        );

        assert!(
            registry
                .consume(
                    grant.token,
                    EffectKind::DeliverLocal,
                    changed_revision,
                    "/tmp/master.otio",
                )
                .is_err()
        );

        let grant = registry
            .issue(EffectKind::DeliverLocal, scope, "/tmp/master.otio")
            .unwrap();
        assert!(
            registry
                .consume(
                    grant.token,
                    EffectKind::DeliverLocal,
                    scope,
                    "/tmp/other.otio",
                )
                .is_err()
        );
    }

    #[test]
    fn expired_grant_fails_closed_without_sleeping() {
        let registry = EffectGrantRegistry::default();
        let scope = scope();
        let grant = registry
            .issue_until(EffectKind::RenderLocal, scope, "render:job", Instant::now())
            .unwrap();

        assert!(
            registry
                .consume(grant.token, EffectKind::RenderLocal, scope, "render:job",)
                .is_err()
        );
    }

    #[test]
    fn unsupported_external_effects_cannot_be_granted() {
        let registry = EffectGrantRegistry::default();
        let scope = scope();
        for effect in [
            EffectKind::RemoteEgress,
            EffectKind::UploadExternal,
            EffectKind::InstallRuntime,
            EffectKind::PublishExternal,
        ] {
            let error = registry.issue(effect, scope, "external").unwrap_err();
            assert!(error.contains("does not expose grants"));
        }
    }

    #[test]
    fn project_import_is_the_only_supported_unscoped_grant() {
        let registry = EffectGrantRegistry::default();
        let unscoped = EffectScope::unscoped_import();
        let grant = registry
            .issue(
                EffectKind::ImportLocal,
                unscoped,
                "/tmp/project.motionwright",
            )
            .unwrap();
        registry
            .consume(
                grant.token,
                EffectKind::ImportLocal,
                unscoped,
                "/tmp/project.motionwright",
            )
            .unwrap();

        assert!(
            registry
                .issue(EffectKind::ProjectEdit, unscoped, "edit")
                .is_err()
        );
        assert!(
            registry
                .issue(EffectKind::ProjectCreate, unscoped, "create")
                .is_err()
        );
    }

    #[test]
    fn creation_is_exactly_one_time_in_its_trusted_workspace_session() {
        let registry = EffectGrantRegistry::default();
        let scope = EffectScope::project_creation(Uuid::now_v7());
        let subject = project_creation_subject("main", "create-1", "A director's project").unwrap();
        let grant = registry
            .issue(EffectKind::ProjectCreate, scope, &subject)
            .unwrap();
        assert_eq!(grant.workspace_session, scope.workspace_session);
        assert_eq!(grant.project_id, None);
        assert_eq!(grant.generation, None);
        assert_eq!(grant.revision, None);
        registry
            .consume(grant.token, EffectKind::ProjectCreate, scope, &subject)
            .unwrap();
        assert!(
            registry
                .consume(grant.token, EffectKind::ProjectCreate, scope, &subject)
                .is_err()
        );
    }

    #[test]
    fn creation_cannot_cross_workspace_registry_window_key_or_original_title() {
        let registry = EffectGrantRegistry::default();
        let scope = EffectScope::project_creation(Uuid::now_v7());
        let subject = project_creation_subject("main", "create-1", "  Original title  ").unwrap();
        for (changed_scope, changed_subject) in [
            (
                EffectScope::project_creation(Uuid::now_v7()),
                subject.clone(),
            ),
            (
                scope,
                project_creation_subject("second", "create-1", "  Original title  ").unwrap(),
            ),
            (
                scope,
                project_creation_subject("main", "create-2", "  Original title  ").unwrap(),
            ),
            (
                scope,
                project_creation_subject("main", "create-1", "Original title").unwrap(),
            ),
        ] {
            let grant = registry
                .issue(EffectKind::ProjectCreate, scope, &subject)
                .unwrap();
            assert!(
                registry
                    .consume(
                        grant.token,
                        EffectKind::ProjectCreate,
                        changed_scope,
                        &changed_subject
                    )
                    .is_err()
            );
            assert!(
                registry
                    .consume(grant.token, EffectKind::ProjectCreate, scope, &subject)
                    .is_err()
            );
        }
        let grant = registry
            .issue(EffectKind::ProjectCreate, scope, &subject)
            .unwrap();
        assert!(
            EffectGrantRegistry::default()
                .consume(grant.token, EffectKind::ProjectCreate, scope, &subject)
                .is_err()
        );
        registry
            .consume(grant.token, EffectKind::ProjectCreate, scope, &subject)
            .unwrap();
    }

    #[test]
    fn creation_scope_never_grants_an_existing_project_or_another_effect() {
        let registry = EffectGrantRegistry::default();
        let creation_scope = EffectScope::project_creation(Uuid::now_v7());
        let subject = project_creation_subject("main", "request", "Project").unwrap();
        assert!(
            registry
                .issue(EffectKind::ProjectCreate, scope(), &subject)
                .is_err()
        );
        assert!(
            registry
                .issue(
                    EffectKind::ProjectCreate,
                    EffectScope::project_creation(Uuid::nil()),
                    &subject
                )
                .is_err()
        );
        let malformed = EffectScope {
            workspace_session: creation_scope.workspace_session,
            ..scope()
        };
        assert!(
            registry
                .issue(EffectKind::ProjectCreate, malformed, &subject)
                .is_err()
        );
        for effect in [
            EffectKind::ProjectEdit,
            EffectKind::ImportLocal,
            EffectKind::RenderLocal,
            EffectKind::DeliverLocal,
            EffectKind::WorkflowMutation,
        ] {
            assert!(registry.issue(effect, creation_scope, &subject).is_err());
            assert!(registry.issue(effect, malformed, &subject).is_err());
        }
    }

    #[test]
    fn creation_subject_preserves_structural_boundaries_and_rejects_invalid_identity() {
        assert_ne!(
            project_creation_subject("a:b", "c", "d").unwrap(),
            project_creation_subject("a", "b:c", "d").unwrap()
        );
        assert_ne!(
            project_creation_subject("main", "same", "é").unwrap(),
            project_creation_subject("main", "same", "e\u{301}").unwrap()
        );
        for invalid in ["", " ", "main\nother"] {
            assert!(project_creation_subject(invalid, "request", "Title").is_err());
            assert!(project_creation_subject("main", invalid, "Title").is_err());
        }
    }

    #[test]
    fn creation_expiry_and_previous_receipt_wire_shape_remain_explicit() {
        let registry = EffectGrantRegistry::default();
        let scope = EffectScope::project_creation(Uuid::now_v7());
        let subject = project_creation_subject("main", "request", "Title").unwrap();
        let grant = registry
            .issue_until(EffectKind::ProjectCreate, scope, &subject, Instant::now())
            .unwrap();
        assert!(
            registry
                .consume(grant.token, EffectKind::ProjectCreate, scope, &subject)
                .is_err()
        );
        let old = registry
            .issue(
                EffectKind::ImportLocal,
                EffectScope::unscoped_import(),
                "bundle",
            )
            .unwrap();
        assert!(
            serde_json::to_value(old)
                .unwrap()
                .get("workspace_session")
                .is_none()
        );
    }
}
