import {expect,test} from "@playwright/test";
import {proposalButton as button,readStudioProject} from "./support/scopedPaintMotionJourney";
test("Save and reopen a bounded music source window without pretending to render audio",async({page})=>{
  await page.goto("/");
  const before=await readStudioProject(page);
  const profile=before.deliverables[0];
  const music=before.assets.find(a=>a.media_type==="audio/wav")!;
  const panel=page.getByRole("region",{name:"Original three-bus native PCM audition",exact:true});
  const open=async()=>{
    await button(page,"Audio").click();
    const expand=panel.getByRole("button",{name:/original source mix/});
    if(await expand.getAttribute("aria-expanded")!=="true") await expand.click();
    await panel.getByLabel("Delivery language / profile",{exact:true}).selectOption(profile.id);
  };
  await open();
  await panel.getByLabel("Enable original mix recipe",{exact:true}).check();
  await panel.getByLabel("Original music asset",{exact:true}).selectOption(music.id);
  const offset=panel.getByLabel("Music source start sample",{exact:true});
  const save=panel.getByRole("button",{name:"Save original mix recipe",exact:true});
  await offset.fill("1e");
  await expect(save).toBeDisabled();
  await button(page,"Canvas").click();await open();
  await expect(offset).toHaveValue("1e");
  await offset.fill("48000");
  await expect(save).toBeEnabled();await save.click();
  await expect(page.locator(".command-bar .revision-chip")).toHaveText("r"+(before.revision+1));
  const after=await readStudioProject(page);
  expect(after.production_design?.delivery_recipes?.[profile.id].original_mix).toMatchObject({music_asset_id:music.id,music_source_start_sample:48000});
  expect(after.scenes).toEqual(before.scenes);expect(after.assets).toEqual(before.assets);expect(after.audio).toEqual(before.audio);
  await button(page,"Canvas").click();await open();
  await expect(offset).toHaveValue("48000");
  await expect(panel.getByLabel("Saved music source window",{exact:true})).toContainText("48000");
  await expect(panel.getByRole("button",{name:"Create local original PCM audition",exact:true})).toBeDisabled();
  await offset.fill("");await save.click();
  await expect(page.locator(".command-bar .revision-chip")).toHaveText("r"+(after.revision+1));
  const cleared=await readStudioProject(page);
  expect(Object.hasOwn(cleared.production_design!.delivery_recipes![profile.id].original_mix!,"music_source_start_sample")).toBe(false);
  expect(cleared.assets).toEqual(before.assets);
});
