import {expect,test} from "@playwright/test";
import {proposalButton as button,readStudioProject} from "./support/scopedPaintMotionJourney";
test("map original marked beats onto the saved music window without moving source marks",async({page})=>{
  await page.goto("/");
  const original=await readStudioProject(page);
  const music=original.assets.find(a=>a.media_type==="audio/wav")!;
  const profile=original.deliverables[0];
  await button(page,"Audio").click();
  const mix=page.getByRole("region",{name:"Original three-bus native PCM audition",exact:true});
  await mix.getByRole("button",{name:/original source mix/}).click();
  await mix.getByLabel("Delivery language / profile",{exact:true}).selectOption(profile.id);
  await mix.getByLabel("Enable original mix recipe",{exact:true}).check();
  await mix.getByLabel("Original music asset",{exact:true}).selectOption(music.id);
  await mix.getByLabel("Music source start sample",{exact:true}).fill("24000");
  await mix.getByRole("button",{name:"Save original mix recipe",exact:true}).click();
  await expect(page.locator(".command-bar .revision-chip")).toHaveText("r"+(original.revision+1));
  await button(page,"Production").click();await button(page,"Production plan").click();
  await page.getByLabel("Production governing clock").selectOption("music");
  await page.getByLabel("Music source asset",{exact:true}).selectOption(music.id);
  const marks="0.000\n6.000\n18.000\n30.000\n42.000";
  await page.getByLabel("Music beat timestamps",{exact:true}).fill(marks);
  await button(page,"Use marked times in plan draft").click();await button(page,"Save production plan").click();
  await expect(page.locator(".command-bar .revision-chip")).toHaveText("r"+(original.revision+2));
  await expect(page.getByLabel("Music source to timeline mapping",{exact:true})).toContainText("Source sample 24000");
  const before=await readStudioProject(page);
  await page.getByLabel("Music cut target scene",{exact:true}).selectOption({label:"Pixels are brittle"});
  const beat=page.getByLabel("Music cut target beat",{exact:true});
  await beat.selectOption("0");
  await expect(button(page,"Apply this scoped musical cut")).toBeDisabled();
  await beat.selectOption("2");
  await expect(beat.locator("option:checked")).toContainText("18.000s source");
  await expect(beat.locator("option:checked")).toContainText("17.500s timeline");
  await expect(page.getByLabel("Music cut impact preview",{exact:true})).toContainText("17.500s");
  const acknowledge=page.getByLabel("Acknowledge fixed audio and marker times",{exact:true});
  if(await acknowledge.isVisible())await acknowledge.check();
  await button(page,"Apply this scoped musical cut").click();
  await expect(page.locator(".command-bar .revision-chip")).toHaveText("r"+(before.revision+1));
  const after=await readStudioProject(page);
  expect(after.scenes[2].start).toEqual({num:"35",den:"2"});
  expect(after.production_design?.plan?.clock).toEqual(before.production_design?.plan?.clock);
  expect(after.production_design?.delivery_recipes).toEqual(before.production_design?.delivery_recipes);
  expect(after.audio).toEqual(before.audio);expect(after.markers).toEqual(before.markers);
  expect(after.assets).toEqual(before.assets);
  await expect(page.getByLabel("Music beat timestamps",{exact:true})).toHaveValue(marks);
});
