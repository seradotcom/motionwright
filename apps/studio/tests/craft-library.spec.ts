test("library previews the real generator and explicitly loads a recoverable authoring draft",async({page})=>{
  await page.goto("/");
  await button(page,"Add scene").click();await page.getByLabel("New scene name").fill("Craft library source");await button(page,"Add").click();
  await button(page,"Production").click();await page.getByLabel("Production working scene").selectOption({label:"Craft library source"});
  const original=await readStudioProject(page);
  await button(page,"Craft library").click();
  const library=page.getByRole("region",{name:"Craft component library",exact:true});
  await expect(library.getByRole("navigation",{name:"Craft definitions"}).getByRole("button")).toHaveCount(36);
  await library.getByLabel("Craft family").selectOption("data");
  await library.getByRole("button",{name:/Series reveal/}).click();
  await expect(library.getByRole("button",{name:"Open authoring editor"})).toHaveCount(0);
  await expect(library.getByText("No preview or install action is available for this unimplemented definition.")).toBeVisible();
  await library.getByLabel("Craft family").selectOption("typography");
  await library.getByRole("button",{name:/Headline focus/}).click();
  await library.getByRole("button",{name:"9:16",exact:true}).click();
  const study=library.getByRole("img",{name:"Headline focus library source study",exact:true});
  await expect(study).toBeVisible();await expect(study.locator("[data-canvas-node-id]")).toHaveCount(6);
  await library.getByRole("button",{name:"Open authoring editor",exact:true}).click();
  expect(await readStudioProject(page)).toEqual(original);
  await expect(button(page,"Load library example")).toBeEnabled();await button(page,"Load library example").click();
  await expect(page.getByLabel("Component layout")).toHaveValue("typography_focus");
  await expect(page.getByLabel("Headline",{exact:true})).toHaveValue("A clear idea");
  expect(await readStudioProject(page)).toEqual(original);
  await expect(button(page,"Add to scene")).toBeEnabled();await button(page,"Add to scene").click();
  await expect(button(page,"Update component")).toBeVisible();
  const saved=await readStudioProject(page),scene=saved.scenes.find(item=>item.name==="Craft library source")!;
  expect(saved.revision).toBe(original.revision+1);
  expect(scene.nodes).toHaveLength(6);
  expect(saved.production_design?.heroes.find(item=>item.scene_id===scene.id)?.config.layout).toBe("typography_focus");
  await expect(button(page,"Load library example")).toBeDisabled();
});

test("library focus transfer stages and reviews two exact opacity tracks in one reversible source revision",async({page})=>{
  await page.goto("/");
  await button(page,"Add scene").click();await page.getByLabel("New scene name").fill("Original focus scene");await button(page,"Add").click();
  await button(page,"Canvas").click();await page.locator(".tree-row").filter({hasText:"Original focus scene"}).click();
  for(let i=0;i<3;i++)await page.getByLabel("Create canvas object",{exact:true}).getByRole("button",{name:"rectangle",exact:true}).click();
  const base=await readStudioProject(page),scene=base.scenes.find(item=>item.name==="Original focus scene")!;
  expect(scene.nodes).toHaveLength(3);
  await button(page,"Production").click();await page.getByLabel("Production working scene").selectOption(scene.id);
  await button(page,"Craft library").click();await page.getByLabel("Craft family").selectOption("transition");
  await page.getByRole("button",{name:/^Focus transfer/}).click();
  await button(page,"Open authoring editor").click();
  await page.getByText("Focus transfer",{exact:true}).click();
  await page.getByLabel("Focus transfer from",{exact:true}).selectOption(scene.nodes[0].id);
  await page.getByLabel("Focus transfer to",{exact:true}).selectOption(scene.nodes[1].id);
  await page.getByLabel("Focus transfer start frame",{exact:true}).fill("0");
  await page.getByLabel("Focus transfer end frame",{exact:true}).fill("30");
  await page.getByLabel("Focus transfer curve",{exact:true}).selectOption("linear");
  await expect(button(page,"Stage focus transfer")).toBeEnabled();await button(page,"Stage focus transfer").click();
  await expect(page.getByRole("region",{name:"Proposed edits",exact:true}).getByLabel(/Remove proposed edit/)).toHaveCount(2);
  expect(await readStudioProject(page)).toEqual(base);
  await button(page,"Preview scoped changes").click();await expect(page.getByText("Editorial diff prepared",{exact:true})).toBeVisible();
  await page.getByLabel("Comparison playhead",{exact:true}).fill("0.5");
  const after=page.getByRole("img",{name:"After scoped changes",exact:true});
  for(const node of scene.nodes.slice(0,2))await expect(after.locator('[data-canvas-node-id="'+node.id+'"]')).toHaveAttribute("opacity","0.5");
  await expect(after.locator('[data-canvas-node-id="'+scene.nodes[2].id+'"]')).toHaveAttribute("opacity","1");
  await button(page,"Apply as one revision").click();
  await expect(page.locator(".command-bar .revision-chip")).toHaveText("r"+(base.revision+1));
  const saved=await readStudioProject(page),nodes=saved.scenes.find(item=>item.id===scene.id)!.nodes;
  expect(nodes[0].keyframes.map(key=>key.value)).toEqual([1,0]);
  expect(nodes[1].keyframes.map(key=>key.value)).toEqual([0,1]);
  expect(nodes[2]).toEqual(scene.nodes[2]);
  await undoArrangement(page,base.revision+2);
  expect((await readStudioProject(page)).scenes.find(item=>item.id===scene.id)!.nodes).toEqual(scene.nodes);
});
