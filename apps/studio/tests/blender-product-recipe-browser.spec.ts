import { expect,test } from "@playwright/test";
import { readFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { proposalButton as button,readStudioProject } from "./support/scopedPaintMotionJourney";
import { authorBlenderRecipe,downloadBlenderRecipe,openBlenderRecipe,recipePanel,sourcePanel } from "./support/blenderRecipeJourney";
test("Author exact Blender product recipe and recover raw controls without native authority",async({page})=>{
  await page.goto("/");
  const original=await readStudioProject(page);
  const incompatible=original.scenes.find(s=>s.renderer==="blender")!;
  await openBlenderRecipe(page,incompatible.id);
  await expect(recipePanel(page).getByRole("button",{name:"Download recipe and prepare source input"})).toBeDisabled();
  await button(page,"Canvas").click();await button(page,"Add scene").click();
  await page.getByLabel("New scene name",{exact:true}).fill("Product recipe study");await button(page,"Add").click();
  await expect(page.locator(".tree-row").filter({hasText:"Product recipe study"})).toBeVisible();
  await page.locator(".tree-row").filter({hasText:"Product recipe study"}).click();
  await page.getByLabel("Renderer",{exact:true}).selectOption("blender");
  await expect.poll(async()=>(await readStudioProject(page)).scenes.find(s=>s.name==="Product recipe study")?.renderer).toBe("blender");
  await page.getByLabel("Scene duration seconds",{exact:true}).fill("40");
  await button(page,"Ripple").click();
  await expect.poll(async()=>(await readStudioProject(page)).scenes.find(s=>s.name==="Product recipe study")?.duration.num).toBe("40");
  const prepared=await readStudioProject(page),scene=prepared.scenes.find(s=>s.name==="Product recipe study")!;
  await openBlenderRecipe(page,scene.id);await authorBlenderRecipe(page);
  await recipePanel(page).getByLabel("Surface roughness",{exact:true}).fill("1e");
  await expect(recipePanel(page).getByRole("button",{name:"Download recipe and prepare source input"})).toBeDisabled();
  await button(page,"Canvas").click();await openBlenderRecipe(page,scene.id);
  await expect(recipePanel(page).getByLabel("Surface roughness",{exact:true})).toHaveValue("1e");
  await recipePanel(page).getByLabel("Surface roughness",{exact:true}).fill("0.37");
  const download=await downloadBlenderRecipe(page);
  expect(download.suggestedFilename()).toBe("blender-product-StudioVessel.json");
  const bytes=await readFile((await download.path())!);
  expect(JSON.parse(bytes.toString("utf8"))).toMatchObject({version:1,namespace:"StudioVessel",coating:"graphite",roughness:0.37,metallic:0.72,samples:96,annotation:"AUTHOR SOURCE\nGRAPHITE",camera_curve:"linear"});
  const hash=createHash("sha256").update(bytes).digest("hex");
  await expect(recipePanel(page).getByLabel("Authored recipe file binding")).toContainText(hash);
  await expect(sourcePanel(page).getByLabel("Source media type",{exact:true})).toHaveValue("application/vnd.motionwright.blender-product+json");
  await expect(sourcePanel(page).getByLabel("Source file name",{exact:true})).toHaveValue(download.suggestedFilename());
  await expect(button(page,"Save source and capsule")).toBeDisabled();
  expect(await page.evaluate(()=>Object.keys(localStorage).filter(k=>k.startsWith("motionwright.file-import.intent.v1:")))).toEqual([]);
  // Browser mode is only a source authoring fixture, not a Service or native save.
  expect((await readStudioProject(page)).assets).toEqual(prepared.assets);
});
