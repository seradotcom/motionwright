import { expect,test } from "@playwright/test";
import { proposalButton as button, readStudioProject } from "./support/scopedPaintMotionJourney";

test("Explicit family propagation changes only the chosen profile in browser Studio", async ({page}) => {
  await page.goto("/");
  await button(page,"Deliver").click();
  const initial=await readStudioProject(page), root=initial.deliverables[0];
  const select=(id:string)=>page.locator('[data-profile-id="'+id+'"]').click();
  const atRevision=async(revision:number)=>expect(page.locator(".revision-chip")).toHaveText("r"+revision);
  await select(root.id);
  await button(page,"Derive selected").click();
  await atRevision(initial.revision+1);
  const first=await readStudioProject(page), child=first.deliverables.find(p=>p.parent_profile_id===root.id)!;
  expect(child).toBeDefined();
  await select(child.id);
  await button(page,"Derive selected").click();
  await atRevision(first.revision+1);
  const second=await readStudioProject(page), grandchild=second.deliverables.find(p=>p.parent_profile_id===child.id)!;
  expect(grandchild).toBeDefined();
  await select(root.id);
  await page.getByLabel("Brand profile",{exact:true}).fill("Campaign source 2026");
  await button(page,"Save profile").click();
  await atRevision(second.revision+1);
  const before=await readStudioProject(page);
  const panel=page.getByRole("region",{name:"Propagate saved delivery setting",exact:true});
  await expect(panel).toContainText("Campaign source 2026");
  const apply=panel.getByRole("button",{name:"Apply to 1 selected profiles",exact:true});
  await panel.getByRole("checkbox",{name:"Update "+child.name,exact:true}).check();
  await expect(panel.getByRole("checkbox",{name:"Update "+grandchild.name,exact:true})).not.toBeChecked();
  await apply.click();
  await atRevision(before.revision+1);
  const saved=await readStudioProject(page);
  expect(saved.deliverables).toEqual(before.deliverables.map(p=>p.id===child.id?{...p,brand_profile:"Campaign source 2026"}:p));
  await expect(panel.getByRole("checkbox",{name:"Update "+child.name,exact:true})).toBeDisabled();
  await expect(panel.getByRole("checkbox",{name:"Update "+grandchild.name,exact:true})).toBeEnabled();
  await expect(panel.getByRole("region",{name:"Retained delivery family attempt"})).toHaveCount(0);
  const retained=await page.evaluate(()=>Object.keys(localStorage).filter(k=>k.startsWith("motionwright.delivery-family-attempt.v1:")));
  expect(retained).toEqual([]);
});
